def test_mcdm_elided_quote_within_one_sample_verifies():
    # d-pineapple: the judge dropped words inside one sample
    prose = [Line(digest.sample_text("Now, pineapples—they are a nice fruit. They are tropical, "
                                     "vibrant and sweet."))]  # fmt: skip
    assert mcdm.elided_quote_ok("Pineapples. They are tropical, vibrant", "pineapple", prose)


def test_mcdm_elided_quote_never_across_samples_or_without_the_concept():
    two = [Line("Pineapples are on the table."), Line("They are tropical, vibrant.")]
    assert not mcdm.elided_quote_ok("Pineapples. They are tropical, vibrant", "pineapple", two)
    one = [Line("Mangoes—they are a nice fruit. They are tropical, vibrant.")]
    assert not mcdm.elided_quote_ok("Mangoes. They are tropical, vibrant", "pineapple", one)
    assert not mcdm.elided_quote_ok("pineapples are tropical", "pineapple", one)  # one fragment


def test_mcdm_verdict_rescue_is_concept_only():
    opts = ["pineapple", "lion", "Mozart being jealous of Salieri", "bow tie", "kite", "drum"]
    readout = [Line("Now, pineapples—they are a nice fruit. They are tropical, vibrant.")]
    res = {"picks": [{"choice": "A", "quote": "Pineapples. They are tropical, vibrant",
                      "basis": "content_bound"}]}  # fmt: skip
    v = mcdm.verdict(res, opts, [0], readout)
    assert v["own"] == ["pineapple"] and v["n_elided_quote"] == 1
    bad = {
        "picks": [{"choice": "A", "quote": "Pineapples. They are sour", "basis": "content_bound"}]
    }
    assert mcdm.verdict(bad, opts, [0], readout)["own"] == []


def test_mcdm_pin_keys_are_content_words():
    assert mcdm.concept_words("parking garage") == ["parking", "parkings", "garage", "garages"]
    assert mcdm.concept_words("sand dune") == ["sand", "sands", "dune", "dunes"]
    assert mcdm.concept_forms("city") == ["city", "cities"]


