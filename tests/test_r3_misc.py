def test_chain_answer_head_shapes():
    shapes = ("15\n\n**Explanation:**", "**28**", "17```", "24\n</think>", "1. Start", "11.**")
    shapes += ("28 + 6 - 5", "1st step", "8GB", "10.5")
    heads = [chain.answer_head(s) for s in shapes]
    assert heads == [15, 28, 17, 24, None, None, None, None, None, None]


def test_chain_tie_on_answer_heads_fails():
    # chain-w2-d2p-0108 L44: 15 and 17 each head 3 add-chain samples (both from a wrong start)
    ops = chain.op_pattern(["add", "add"])
    cells = [
        Cell(
            "x",
            44,
            59,
            ("15\n\nStarting with 10, add 2 to get 12, then add 3 to get 15.",) * 3,
            None,
            None,
        ),
        Cell(
            "x",
            44,
            63,
            ("17\n\nStarting with 8, adding 3 yields 11, adding 6 gives 17.",) * 3,
            None,
            None,
        ),
    ]
    heads = chain.answer_head_counts(cells, ops)
    opts = [17, 18, 28, 32, 19, 24, 15, 25]
    assert heads == {15: 3, 17: 3} and chain.head_tie(15, opts, heads)
    q = "add 3 to get 15"
    v = chain.summary_verdict_mc(
        {"choice": opts.index(15) + 1, "quote": q},
        15,
        opts,
        digest.native_lines(cells),
        None,
        heads,
    )
    assert v["kind"] == "tie" and not v["hit"]


def test_chain_unrelated_or_bare_rival_heads_do_not_tie():
    # chain-d2p-0383 L44: the "6" heads are about other tasks; chain-w2-d2p-0014: a bare "12"
    ops = chain.op_pattern(["halve_up", "halve_up"])
    cells = [
        Cell("x", 44, 65, ("13\n\nRound up half of 25: 12.5 -> 13",) * 2, None, None),
        Cell("x", 44, 64, ("6\n\n1. Identify the odd-indexed days in March 2023", "6"), None, None),
    ]
    heads = chain.answer_head_counts(cells, ops)
    assert heads == {13: 2} and not chain.head_tie(13, [6, 12, 4, 11, 8, 9, 13, 10], heads)
    # heads-v3: a gold with no counted head is held to the one-head bar (no quote exemption)
    assert chain.head_tie(26, [22, 24, 26], {22: 4})
    assert not chain.head_tie(26, [22, 24, 26], {})
    # a rival LEAD (more heads than the gold) fails
    assert chain.head_tie(10, [24, 10], {10: 2, 24: 4})


