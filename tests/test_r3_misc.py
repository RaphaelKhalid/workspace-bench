# ---------------------------------------------------------------- relational_multihop relgate-v3


def _states(text: str, outer: str, inner: str) -> bool:
    return gate.states(gate.fold(text), outer, inner)


def test_rel_blank_touching_a_word_is_a_blank():
    # rel-s38-a / rel-s15-b / rel-s26-a / rel-s25-a: relgate-v2 folded these to the chain
    assert not _states("Ana's son is the barber's ____child.", "barber", "child")
    assert not _states("Lennox is the cousin's________ coach.", "cousin", "coach")
    assert not _states("Caroline is the plumber's _______mother.", "plumber", "parent")
    assert not _states("the barber's ____child and ____son", "barber", "child")


def test_rel_emphasis_and_plain_chains_still_state():
    assert _states("Zoe is the barber's ___child___.", "barber", "child")  # bold-italic word
    assert _states("the __cousin__ of the landlord", "landlord", "cousin")
    assert _states("Zoe is the barber's child.", "barber", "child")
    assert "~blank~" not in gate.fold("a snake_case token")  # a lone _ inside a word


# ---------------------------------------------------------------- knowledge_cutoff kcgate-v2


def _rules(gold: str, options: list[str], units: dict | None = None) -> kc.ItemRules:
    units = units or {}
    return kc.ItemRules.of(
        {
            "id": "x",
            "user": "How many? Answer with just the number.",
            "gold": gold,
            "options": options,
            "option_units": {o: units.get(o, [o]) for o in options},
        }
    )


def _cell(*samples: str, pos: int = -1) -> Cell:
    return Cell("x", 60, pos, tuple(samples), None, None)


def test_kc_tie_of_separate_samples_fails_g3():
    # kc4_00160 lite: "20" and "15" each open 3 samples -> a tie singles out neither
    r = _rules("20", ["20", "15", "200", "30", "49"])
    cells = [_cell("20 per month", "20", "20 dollars", "15", "15 per month", "15 USD")]
    g = kc.gates("20", kc.support(cells, r), r)
    assert g["g2"] and not g["g3"]


def test_kc_lead_and_cooccurrence_still_pass_g3():
    r = _rules("20", ["20", "15", "200", "30", "49"])
    lead = [_cell("20 per month", "20", "20 dollars", "15", "15 per month")]
    assert kc.gates("20", kc.support(lead, r), r)["g3"]
    # a rival only ever named beside the pick is no contest (worked arithmetic)
    r2 = _rules("16384", ["16384", "8192", "4096", "2048", "1024"])
    worked = "16384 (8192 x 2 = 16384, up from 4096)"
    assert kc.gates("16384", kc.support([_cell(worked, worked)], r2), r2)["g3"]


def test_kc_list_numbering_presents_no_option():
    # kc3_00958 / kc3_00345: "1.  **Analyze the Request**", "8.  **The Core Element:**"
    r = _rules("50", ["52", "1", "51", "3", "50"])
    samples = (
        "1.  **Analyze the Request**\n2.  The answer is **50**.",
        "### Step 1: Recall\nKohli has **50** ODI centuries.",
        "Let's reason step by step: 1) How many centuries? **50**.",
    )
    sup = kc.support([_cell(*samples)], r)
    assert sup.counts["1"] == 0 and sup.counts["50"] == 3
    assert kc.gates("50", sup, r)["g3"]
    assert mask_enumerators("8.  **The Core Element:** 24 GB") == "  **The Core Element:** 24 GB"


def test_kc_real_number_mentions_still_present():
    r = _rules("3", ["52", "1", "51", "3", "50"])
    sup = kc.support([_cell("3", "The answer is **3**.", "50.")], r)
    assert sup.counts["3"] == 2 and sup.counts["50"] == 1  # a bare "50." line keeps its number
    assert mask_enumerators("It is 50. Then") == "It is 50. Then"


def test_kc_small_number_word_is_no_support_but_a_unit_form_is():
    assert small_number_word("three") and small_number_word("One")
    assert not small_number_word("three centuries") and not small_number_word("nineteen")
    r = _rules("50", ["52", "1", "51", "3", "50"], {"3": ["3", "three", "three centuries"]})
    sup = kc.support([_cell("generated by three automorphisms", "three centuries in total")], r)
    assert sup.counts["3"] == 1


def test_kc_g1_reads_the_masked_head():
    # the quote's bullet opens with list numbering "1." only: no contradiction of the pick 50
    r = _rules("50", ["52", "1", "51", "3", "50"])
    s = "1.  **Recall the record**: Kohli has 50 ODI centuries"
    cells = [_cell(s)]
    ok, drop, _ub = kc.verify("50", "Kohli has 50 ODI centuries", digest.native_lines(cells),
                              cells, r)  # fmt: skip
    assert ok and drop is None
    # a head that states another option still contradicts
    s2 = "52 (note: Kohli has 50 ODI centuries)"
    cells2 = [_cell(s2)]
    ok2, drop2, _ = kc.verify("50", "Kohli has 50 ODI centuries", digest.native_lines(cells2),
                              cells2, r)  # fmt: skip
    assert not ok2 and drop2 == "contradicted"


