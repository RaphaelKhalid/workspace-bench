"""Regenerate the prompt blocks and bank counts of ``evals/basic_readout_mt/README.md`` (plan
0033) from the code and the frozen v2 bank, so the README never drifts from either.

    .venv/bin/python scripts/brmt_readme.py
"""

import json
from collections import Counter
from pathlib import Path

from wsbench.banks import load_bank
from wsbench.evals.basic_readout_mt.prompts import PROMPTS
from wsbench.multitoken.prompts import BRMT_PROMPT_VERSION

REPO = Path(__file__).resolve().parents[1]
README = REPO / "evals/basic_readout_mt/README.md"
GATE = REPO / "evals/basic_readout_mt/gate_v2.json"

ORDER = [
    ("BRMT_SYSTEM", "the judge's SYSTEM prompt (`mc_system(BRMT_TASK, ...)`)"),
    ("USER", "the native user message"),
    ("BRMT_QUESTION", "the `readout` unit's question"),
    ("QUESTION_LANGUAGE", "the `language` unit's question (reported, never gated on)"),
    ("BRMT_CANNOT", "the cannot-tell option, always last"),
    ("USER_SUMMARY", "the summary-mode user message"),
    ("DIGEST_TASK_NOTE", "the digest's task note (sent by default, `summ_variant=task`)"),
    ("SUMMARY_NOTE", "the judge-side digest note (`summ_render=extractive`)"),
    ("SUMMARY_NOTE_ABSTRACTIVE", "the note under `summ_render=abstractive`"),
    ("SUMMARY_NOTE_TOKENS", "appended when the source readouts are token lists"),
    ("OPTION_AUDIT_SYSTEM", "the option audit's SYSTEM prompt (optaudit-v1, summary mode)"),
    ("OPTION_AUDIT_USER", "the option audit's user message"),
]
MARK = "<!-- prompts: generated by scripts/brmt_readme.py -->"


def counts() -> dict[str, object]:
    header, items = load_bank(REPO / "evals/basic_readout_mt/items_v2.json")
    langs = Counter(it.get("lang") for it in items if it.get("lang"))
    gate = json.loads(GATE.read_text(encoding="utf-8"))
    return {
        "n": len(items),
        "n_entity": sum(1 for it in items if it.get("subfamily") == "entity"),
        "n_l2": sum(1 for it in items if it.get("lang")),
        "langs": ", ".join(f"{k} {v}" for k, v in sorted(langs.items(), key=lambda x: -x[1])),
        "n_langs": len(langs),
        "dropped": gate["dropped"],
        "frozen": header["frozen"],
        "pv": BRMT_PROMPT_VERSION,
    }


def prompt_blocks() -> str:
    out = [MARK, ""]
    for key, what in ORDER:
        out += [f"`{key}` ({what}):", "", "```text", PROMPTS[key], "```", ""]
    missing = set(PROMPTS) - {k for k, _ in ORDER}
    if missing:
        raise SystemExit(f"README order lacks {sorted(missing)}")
    return "\n".join(out)


def main() -> None:
    text = README.read_text(encoding="utf-8")
    c = counts()
    for k, v in c.items():
        text = text.replace("{" + k + "}", str(v))
    head = text.split(MARK, 1)[0].rstrip() + "\n\n"
    README.write_text(head + prompt_blocks(), encoding="utf-8")
    assert BRMT_PROMPT_VERSION in README.read_text(encoding="utf-8")
    print(f"wrote {README} ({c['n']} items)")


if __name__ == "__main__":
    main()
